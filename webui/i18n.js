const LANGS = ['es', 'en'];
const LANG_STORE_KEY = 'wy_lang';
const I18N = { es: {}, en: {} };
for (const [k, pair] of Object.entries(I18N_PAIRS)) { I18N.es[k] = pair[0]; I18N.en[k] = pair[1]; }

// Idioma inicial (sin sesión): localStorage 'wy_lang' → navigator.language (es* → es) → en.
// Con sesión, boot() aplica el idioma guardado en el usuario (users.lang).
function readStoredLang() { try { const v = localStorage.getItem(LANG_STORE_KEY); return LANGS.includes(v) ? v : null; } catch (e) { return null; } }
function storeLang(l) { try { localStorage.setItem(LANG_STORE_KEY, l); } catch (e) {} }
function browserLang() { const n = String((navigator.languages && navigator.languages[0]) || navigator.language || '').toLowerCase(); return n.startsWith('es') ? 'es' : 'en'; }
let LANG = readStoredLang() || browserLang();
document.documentElement.lang = LANG;

// t('clave', { var }) → texto del idioma activo; {var} se sustituye tal cual (escapar antes si va a HTML).
// Valores { one, other }: plural según vars.n. Si falta la clave en 'en' cae a 'es'; si falta en ambos, devuelve la clave.
function t(key, vars) {
  let s = I18N[LANG] && I18N[LANG][key];
  if (s == null) s = I18N.es[key];
  if (s == null) return key;
  if (typeof s === 'object') s = vars && Number(vars.n) === 1 ? s.one : s.other;
  if (!vars) return s;
  return s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
}
// Etiqueta de un diccionario por clave (status.*, loss.*…) con texto de reserva si la clave no existe.
function tk(prefix, key, fallback) {
  const k = `${prefix}.${key}`;
  return (I18N[LANG] && I18N[LANG][k] != null) ? I18N[LANG][k] : (I18N.es[k] != null ? I18N.es[k] : (fallback != null ? fallback : key));
}
